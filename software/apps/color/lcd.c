static void spi_write_cmd(uint8_t cmd) {
    nrf_gpio_pin_clear(LCD_DC);
    nrf_gpio_pin_clear(LCD_CS);
    nrfx_spim_xfer_desc_t xfer = NRFX_SPIM_XFER_TX(&cmd, 1);
    nrfx_spim_xfer(&spi, &xfer, 0);
    nrf_gpio_pin_set(LCD_CS);
}

static void spi_write_data(uint8_t data) {
    nrf_gpio_pin_set(LCD_DC);
    nrf_gpio_pin_clear(LCD_CS);
    nrfx_spim_xfer_desc_t xfer = NRFX_SPIM_XFER_TX(&data, 1);
    nrfx_spim_xfer(&spi, &xfer, 0);
    nrf_gpio_pin_set(LCD_CS);
}

static void lcd_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1) {
    spi_write_cmd(0x2A);
    spi_write_data(x0 >> 8); spi_write_data(x0 & 0xFF);
    spi_write_data(x1 >> 8); spi_write_data(x1 & 0xFF);

    spi_write_cmd(0x2B);
    spi_write_data(y0 >> 8); spi_write_data(y0 & 0xFF);
    spi_write_data(y1 >> 8); spi_write_data(y1 & 0xFF);

    spi_write_cmd(0x2C);
}

void lcd_init(void) {
    nrf_gpio_cfg_output(LCD_CS);
    nrf_gpio_cfg_output(LCD_DC);
    nrf_gpio_cfg_output(LCD_RST);
    nrf_gpio_pin_set(LCD_CS);

    nrfx_spim_config_t spi_config = NRFX_SPIM_DEFAULT_CONFIG;
    spi_config.sck_pin  = EDGE_P13;
    spi_config.mosi_pin = EDGE_P15;
    spi_config.miso_pin = NRFX_SPIM_PIN_NOT_USED;
    spi_config.frequency = NRF_SPIM_FREQ_8M;
    spi_config.mode = NRF_SPIM_MODE_0;
    APP_ERROR_CHECK(nrfx_spim_init(&spi, &spi_config, NULL, NULL));

    nrf_gpio_pin_clear(LCD_RST);
    nrf_delay_ms(10);
    nrf_gpio_pin_set(LCD_RST);
    nrf_delay_ms(120);

    spi_write_cmd(0x01);
    nrf_delay_ms(150);
    spi_write_cmd(0x11);
    nrf_delay_ms(500);
    spi_write_cmd(0x3A);
    spi_write_data(0x55);
    spi_write_cmd(0x36);
    spi_write_data(0x88); // 180 degree rotation
    spi_write_cmd(0x29);
    nrf_delay_ms(100);
}

void lcd_fill_screen(uint16_t color) {
    lcd_set_window(0, 0, 239, 319);

    nrf_gpio_pin_set(LCD_DC);
    nrf_gpio_pin_clear(LCD_CS);

    uint8_t buf[32];
    for (int i = 0; i < 16; i++) {
        buf[i * 2]     = color >> 8;
        buf[i * 2 + 1] = color & 0xFF;
    }

    for (uint32_t i = 0; i < (240 * 320) / 16; i++) {
        nrfx_spim_xfer_desc_t xfer = NRFX_SPIM_XFER_TX(buf, 32);
        nrfx_spim_xfer(&spi, &xfer, 0);
    }

    nrf_gpio_pin_set(LCD_CS);
}

void lcd_fill_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color) {
    if (x >= 240 || y >= 320) return;
    if (x + w > 240) w = 240 - x;
    if (y + h > 320) h = 320 - y;

    lcd_set_window(x, y, x + w - 1, y + h - 1);

    nrf_gpio_pin_set(LCD_DC);
    nrf_gpio_pin_clear(LCD_CS);

    uint8_t hi = color >> 8;
    uint8_t lo = color & 0xFF;
    uint8_t buf[32];
    for (int i = 0; i < 16; i++) {
        buf[i * 2]     = hi;
        buf[i * 2 + 1] = lo;
    }

    uint32_t total = (uint32_t)w * h;
    uint32_t full = total / 16;
    uint32_t rem  = total % 16;

    for (uint32_t i = 0; i < full; i++) {
        nrfx_spim_xfer_desc_t xfer = NRFX_SPIM_XFER_TX(buf, 32);
        nrfx_spim_xfer(&spi, &xfer, 0);
    }
    if (rem > 0) {
        nrfx_spim_xfer_desc_t xfer = NRFX_SPIM_XFER_TX(buf, rem * 2);
        nrfx_spim_xfer(&spi, &xfer, 0);
    }

    nrf_gpio_pin_set(LCD_CS);
}

void lcd_draw_char(uint16_t x, uint16_t y, char c, uint16_t fg, uint16_t bg) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t* glyph = font5x7[c - 32];

    // Each char is 6 wide (5 + 1 spacing) and 8 tall
    lcd_set_window(x, y, x + 5, y + 7);

    nrf_gpio_pin_set(LCD_DC);
    nrf_gpio_pin_clear(LCD_CS);

    uint8_t pixel[2];
    for (uint8_t row = 0; row < 8; row++) {
        for (uint8_t col = 0; col < 6; col++) {
            bool on = false;
            if (col < 5) {
                on = (glyph[col] >> row) & 1;
            }
            uint16_t color = on ? fg : bg;
            pixel[0] = color >> 8;
            pixel[1] = color & 0xFF;
            nrfx_spim_xfer_desc_t xfer = NRFX_SPIM_XFER_TX(pixel, 2);
            nrfx_spim_xfer(&spi, &xfer, 0);
        }
    }

    nrf_gpio_pin_set(LCD_CS);
}

void lcd_draw_string(uint16_t x, uint16_t y, const char* str, uint16_t fg, uint16_t bg) {
    while (*str) {
        if (x + 6 > 240) break;
        lcd_draw_char(x, y, *str, fg, bg);
        x += 6;
        str++;
    }
}

void lcd_draw_string_2x(uint16_t x, uint16_t y, const char* str, uint16_t fg, uint16_t bg) {
    while (*str) {
        char c = *str;
        if (c < 32 || c > 126) c = '?';
        const uint8_t* glyph = font5x7[c - 32];

        // 2x scale so 12 wide (10 + 2 spacing) and 16 tall now
        lcd_set_window(x, y, x + 11, y + 15);

        nrf_gpio_pin_set(LCD_DC);
        nrf_gpio_pin_clear(LCD_CS);

        uint8_t pixel[2];
        for (uint8_t row = 0; row < 8; row++) {
            // Each font row drawn twice for doublin vert
            for (int dup = 0; dup < 2; dup++) {
                for (uint8_t col = 0; col < 6; col++) {
                    bool on = false;
                    if (col < 5) {
                        on = (glyph[col] >> row) & 1;
                    }
                    uint16_t color = on ? fg : bg;
                    pixel[0] = color >> 8;
                    pixel[1] = color & 0xFF;
                    // Each pixel drawn twice for doubling horizontal
                    nrfx_spim_xfer_desc_t xfer = NRFX_SPIM_XFER_TX(pixel, 2);
                    nrfx_spim_xfer(&spi, &xfer, 0);
                    nrfx_spim_xfer(&spi, &xfer, 0);
                }
            }
        }

        nrf_gpio_pin_set(LCD_CS);
        x += 12;
        if (x + 12 > 240) break;
        str++;
    }
}
